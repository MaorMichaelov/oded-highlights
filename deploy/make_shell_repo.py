#!/usr/bin/env python3
"""Generates the files of the PUBLIC "workflow shell" repo (design in docs/DEPLOY_PRIVATE_SERVER.md, option C). It only READS this checkout and WRITES into --out; it creates no repository, changes no visibility, uses no network.

The shell repo contains: .github/workflows/*.yml (copied, with every plain `actions/checkout@v4` followed by a step that pulls the PRIVATE code repo with a read-only deploy key), the composite action that does the pulling,
state/ (the loops' committed state, optional) and a README. It does NOT contain scripts/, config/, assets/, app/ (those stay in the private repo and are copied into the workspace at run time).
usage: make_shell_repo.py --out ../oded-highlights-shell --code-repo OWNER/PRIVATE_REPO [--ref main] [--with-state]
Then follow docs/DEPLOY_PRIVATE_SERVER.md section 5 (the owner creates the repos and secrets by hand)."""
import argparse, glob, os, re, shutil, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CHECKOUT = re.compile(r"^(?P<ind>[ ]*)- uses: actions/checkout@v4[ ]*$")
CODE_DIRS = ["scripts", "config", "assets", "app", "tests"]

ACTION = """name: get-code
description: Copy the private code repo (scripts, config, assets, app) into the workspace. Read-only deploy key; the key is a secret of THIS repo.
inputs:
  key: {{ description: "SSH private key (deploy key, read-only) of the code repo", required: true }}
runs:
  using: composite
  steps:
    - uses: actions/checkout@v4
      with:
        repository: {repo}
        ref: {ref}
        ssh-key: ${{{{ inputs.key }}}}
        path: _code
        persist-credentials: false
    - shell: bash
      run: |
        set -e
        for d in {dirs}; do [ -d "_code/$d" ] && cp -a "_code/$d" . ; done
        rm -rf _code
"""


def rewrite_workflow(text):
    """every plain checkout step gets the get-code step right behind it; returns (new_text, count)"""
    out, n = [], 0
    for line in text.splitlines():
        out.append(line); m = CHECKOUT.match(line)
        if m:
            i = m.group("ind"); out += [i + "- uses: ./.github/actions/get-code", i + "  with: { key: \"${{ secrets.CODE_DEPLOY_KEY }}\" }"]; n += 1
    return "\n".join(out) + ("\n" if text.endswith("\n") else ""), n


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0]); ap.add_argument("--out", required=True); ap.add_argument("--code-repo", required=True, help="OWNER/NAME of the private code repo")
    ap.add_argument("--ref", default="main"); ap.add_argument("--with-state", action="store_true", help="also copy state/ (the committed loop state, about 4 MB)"); a = ap.parse_args(argv)
    if not re.fullmatch(r"[A-Za-z0-9_.-]+/[A-Za-z0-9_.-]+", a.code_repo): print("--code-repo must look like OWNER/NAME", file=sys.stderr); return 2
    out = os.path.abspath(a.out)
    if os.path.exists(out) and os.listdir(out): print("refusing to write into a non-empty directory:", out, file=sys.stderr); return 2
    wf_out = os.path.join(out, ".github", "workflows"); act_out = os.path.join(out, ".github", "actions", "get-code"); os.makedirs(wf_out); os.makedirs(act_out)
    total, touched, plain = 0, 0, []
    for f in sorted(glob.glob(os.path.join(ROOT, ".github", "workflows", "*.yml"))):
        text = open(f, encoding="utf-8").read(); new, n = rewrite_workflow(text); total += n; touched += bool(n)
        if not n and "actions/checkout" in text: plain.append(os.path.basename(f))   # checkout with options: needs a manual look
        open(os.path.join(wf_out, os.path.basename(f)), "w", encoding="utf-8").write(new)
    open(os.path.join(act_out, "action.yml"), "w").write(ACTION.format(repo=a.code_repo, ref=a.ref, dirs=" ".join(CODE_DIRS)))
    if a.with_state and os.path.isdir(os.path.join(ROOT, "state")): shutil.copytree(os.path.join(ROOT, "state"), os.path.join(out, "state"), ignore=shutil.ignore_patterns("UPLOAD_HOLD.tmp"))
    open(os.path.join(out, "README.md"), "w").write("# workflow shell\n\nOnly GitHub Actions workflows and loop state live here (public repos get free Actions minutes). The code is in a private repository and is pulled in at run time with a read-only deploy key (secret `CODE_DEPLOY_KEY`).\nGenerated by deploy/make_shell_repo.py.\n")
    open(os.path.join(out, ".gitignore"), "w").write("_code/\nscripts/\nconfig/\nassets/\napp/\ntests/\n__pycache__/\n*.pyc\n")   # the copied code must never be committed into the public repo
    try:
        import yaml
        for f in glob.glob(os.path.join(wf_out, "*.yml")) + [os.path.join(act_out, "action.yml")]: yaml.safe_load(open(f, encoding="utf-8"))
        print("all generated YAML parses")
    except ImportError: print("PyYAML not installed: YAML not validated")
    print("workflows: %d, checkout steps rewritten: %d in %d files" % (len(glob.glob(os.path.join(wf_out, "*.yml"))), total, touched))
    if plain: print("CHECK BY HAND (checkout with options):", ", ".join(plain))
    print("written to", out); return 0


if __name__ == "__main__": sys.exit(main())
